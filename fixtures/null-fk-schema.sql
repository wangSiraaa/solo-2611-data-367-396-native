-- MATCH SIMPLE 部分 NULL 豁免：子行 (a,b) 含 NULL 时不要求父键存在。
PRAGMA foreign_keys=ON;
CREATE TABLE pn(pid INTEGER PRIMARY KEY, a INTEGER NOT NULL, b INTEGER, UNIQUE(a,b));
CREATE TABLE cn(cid INTEGER PRIMARY KEY, a INTEGER NOT NULL, b INTEGER,
  FOREIGN KEY(a,b) REFERENCES pn(a,b) DEFERRABLE INITIALLY DEFERRED);
