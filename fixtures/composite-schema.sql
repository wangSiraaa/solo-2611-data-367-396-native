-- 复合外键整元组陷阱：子元组 (a,b)=(1,2) 的两个分量都能在父表分别找到，
-- 但不存在同一父行 (1,2)，按真实 MATCH SIMPLE 必须判无解。
PRAGMA foreign_keys=ON;
CREATE TABLE pp(pid INTEGER PRIMARY KEY, a INTEGER NOT NULL, b INTEGER NOT NULL, UNIQUE(a,b));
CREATE TABLE cc(cid INTEGER PRIMARY KEY, a INTEGER NOT NULL, b INTEGER NOT NULL,
  FOREIGN KEY(a,b) REFERENCES pp(a,b) DEFERRABLE INITIALLY DEFERRED);
